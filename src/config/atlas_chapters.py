def get_all_sheet_filenames() -> List[str]:
    """返回图册全部图纸文件名扁平列表。"""
    fns = []
    for _, _, sheets in CHAPTERS:
        for fn, _ in sheets:
            fns.append(fn)
    return fns


def get_chapter_by_name(name: str) -> Tuple[str, str, List[Tuple[str, str]]] | None:
    """按中文或英文名检索章节。"""
    for ch_name, ch_en, sheets in CHAPTERS:
        if name in (ch_name, ch_en):
            return (ch_name, ch_en, sheets)
    return None
