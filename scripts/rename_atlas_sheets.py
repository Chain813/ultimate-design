def rename_atlas_files():
    print("Scanning all PNG files in static/atlas (and its subfolders)...")
    
    # First, collect all files recursively
    all_files = []
    for root_dir, dirs, files in os.walk(str(ATLAS_DIR)):
        for f in files:
            if f.lower().endswith(".png"):
                full_path = Path(root_dir) / f
                all_files.append(full_path)
                
    print(f"Found {len(all_files)} files to match.")
    
    renamed_count = 0
    # Map rules to match files
    for old_pattern, new_name in MAPPING_RULES:
        # Check if the destination file already exists and is correct to avoid overwriting or redundant moves
        dst_path = ATLAS_DIR / new_name
        
        # Search in collected files
        matched_file = None
        for fpath in all_files:
            rel_to_atlas = fpath.relative_to(ATLAS_DIR).as_posix()
            if old_pattern in rel_to_atlas:
                matched_file = fpath
                break
                
        if matched_file:
            if matched_file != dst_path:
                print(f" -> Renaming: {matched_file.relative_to(ATLAS_DIR)} -> {new_name}")
                os.makedirs(str(dst_path.parent), exist_ok=True)
                shutil.move(str(matched_file), str(dst_path))
                renamed_count += 1
                # Remove from collected files to avoid double match
                all_files.remove(matched_file)
            else:
                # print(f" -> Already correct: {new_name}")
                pass
        else:
            # print(f" -> Pattern not found: {old_pattern}")
            pass
            
    print(f"Successfully renamed {renamed_count} files.")

if __name__ == "__main__":
    rename_atlas_files()
